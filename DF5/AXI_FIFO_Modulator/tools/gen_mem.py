#!/usr/bin/env python3
"""
gen_mem.py -- генерує таблиці для RTL ($readmemh) і для C-коду.

    vivado/sources/mem/nco_sin_1024.mem   1024 x int16, повний період синуса
                                          (cos = sin з індексом +256)
    vitis/src/dsp/dsp_tables.c            таблиці для DSP у MicroBlaze:
                                          синус 1024/4+1 точок, вікно Ханна 1024

Запускати з каталогу tools/:  python gen_mem.py
"""
import math
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
MEM_DIR = os.path.join(ROOT, "vivado", "sources", "mem")
SRC_DIR = os.path.join(ROOT, "vitis", "src", "dsp")

NCO_N = 1024
FFT_N = 1024


def q15(x):
    v = int(round(x * 32767))
    return max(-32768, min(32767, v))


def main():
    os.makedirs(MEM_DIR, exist_ok=True)
    os.makedirs(SRC_DIR, exist_ok=True)

    # ---------------------------------------------------------------- RTL ---
    path = os.path.join(MEM_DIR, "nco_sin_1024.mem")
    with open(path, "w", encoding="ascii") as f:
        f.write("// nco_sin_1024.mem -- sin(2*pi*k/1024) in Q15, generated by tools/gen_mem.py\n")
        for k in range(NCO_N):
            f.write(f"{q15(math.sin(2 * math.pi * k / NCO_N)) & 0xFFFF:04x}\n")
    print("->", path)

    # ------------------------------------------------------------------ C ---
    path = os.path.join(SRC_DIR, "dsp_tables.c")
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* dsp_tables.c -- ЗГЕНЕРОВАНО tools/gen_mem.py, не редагувати вручну.\n"
                " *\n"
                " * dsp_sin_q15[k] = sin(2*pi*k/1024) для k = 0..256 (чверть періоду + 1),\n"
                " * dsp_hann_q15[n] = 0.5*(1 - cos(2*pi*n/1024)) для n = 0..1023.\n"
                " */\n")
        f.write('#include "dsp/dsp_tables.h"\n\n')
        f.write("const int16_t dsp_sin_q15[DSP_FFT_N / 4 + 1] = {\n")
        vals = [q15(math.sin(2 * math.pi * k / FFT_N)) for k in range(FFT_N // 4 + 1)]
        for i in range(0, len(vals), 12):
            f.write("    " + ", ".join(f"{v:6d}" for v in vals[i:i + 12]) + ",\n")
        f.write("};\n\n")
        f.write("const int16_t dsp_hann_q15[DSP_FFT_N] = {\n")
        vals = [q15(0.5 * (1 - math.cos(2 * math.pi * n / FFT_N))) for n in range(FFT_N)]
        for i in range(0, len(vals), 12):
            f.write("    " + ", ".join(f"{v:6d}" for v in vals[i:i + 12]) + ",\n")
        f.write("};\n")
    print("->", path)

    path = os.path.join(SRC_DIR, "dsp_tables.h")
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* dsp_tables.h -- ЗГЕНЕРОВАНО tools/gen_mem.py, не редагувати вручну. */\n"
                "#ifndef DSP_TABLES_H\n#define DSP_TABLES_H\n\n"
                "#include <stdint.h>\n\n"
                f"#define DSP_FFT_N {FFT_N}\n\n"
                "extern const int16_t dsp_sin_q15[DSP_FFT_N / 4 + 1];\n"
                "extern const int16_t dsp_hann_q15[DSP_FFT_N];\n\n"
                "#endif /* DSP_TABLES_H */\n")
    print("->", path)


if __name__ == "__main__":
    main()
