#!/usr/bin/env python3
"""
gen_mem.py -- генерує таблиці для RTL ($readmemh) і для C-коду.

    vivado/sources/mem/nco_sin_1024.mem   1024 x int16, повний період синуса
                                          (cos = sin з індексом +256)
    vivado/sources/mem/fft_tw128.mem      twiddle FFT-256: {wi, wr} для m = 0..127, як у fft.c
    vivado/sources/mem/fft_hann256.mem    вікно Ханна для FFT-256: dsp_hann_q15[4n+2]
    vivado/sources/mem/gen_gauss.mem      GFSK-імпульс для iq_gen: 3 x 256, Q15
    tools/host_sim/model/dsp/dsp_tables.c таблиці для C-моделі DSP (host_sim):
                                          синус 1024/4+1 точок, вікно Ханна 1024

Запускати з каталогу tools/:  python gen_mem.py
"""
import math
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
MEM_DIR = os.path.join(ROOT, "vivado", "sources", "mem")
SRC_DIR = os.path.join(ROOT, "tools", "host_sim", "model", "dsp")

NCO_N = 1024
FFT_N = 1024


def q15(x):
    v = int(round(x * 32767))
    return max(-32768, min(32767, v))


def main():
    os.makedirs(MEM_DIR, exist_ok=True)
    os.makedirs(SRC_DIR, exist_ok=True)

    # ---------------------------------------------------------------- RTL ---
    path = os.path.join(MEM_DIR, "nco_sin_1024.mem")
    with open(path, "w", encoding="ascii") as f:
        f.write("// nco_sin_1024.mem -- sin(2*pi*k/1024) in Q15, generated by tools/gen_mem.py\n")
        for k in range(NCO_N):
            f.write(f"{q15(math.sin(2 * math.pi * k / NCO_N)) & 0xFFFF:04x}\n")
    print("->", path)

    # FFT-256 у dsp_spectrum: ті самі таблиці, що й у C (spectrum.c / fft.c),
    # щоб RTL збігався з C-моделлю біт у біт
    sin_q = [q15(math.sin(2 * math.pi * k / FFT_N)) for k in range(FFT_N // 4 + 1)]
    hann = [q15(0.5 * (1 - math.cos(2 * math.pi * n / FFT_N))) for n in range(FFT_N)]
    # twiddle метелика: у fft.c ph = k * 65536/len = m * 256, де m = k << (7 - стадія);
    # wr = sin_q15(ph + 16384), wi = -sin_q15(ph) -- рахуємо тут тим самим кодом,
    # RTL лише читає готову пару (одна ROM, без арифметики індексу)
    def sin_q15c(ph):
        idx = (ph >> 6) & 1023
        q, o = idx >> 8, idx & 255
        if q == 0: return sin_q[o]
        if q == 1: return sin_q[256 - o]
        if q == 2: return -sin_q[o]
        return -sin_q[256 - o]
    path = os.path.join(MEM_DIR, "fft_tw128.mem")
    with open(path, "w", encoding="ascii") as f:
        f.write("// fft_tw128.mem -- FFT-256 twiddles {wi[31:16], wr[15:0]}, m = 0..127, tools/gen_mem.py\n")
        for m in range(128):
            ph = m * 256
            wr = sin_q15c((ph + 16384) & 0xFFFF)
            wi = -sin_q15c(ph)
            f.write(f"{((wi & 0xFFFF) << 16) | (wr & 0xFFFF):08x}\n")
    print("->", path)
    path = os.path.join(MEM_DIR, "fft_hann256.mem")
    with open(path, "w", encoding="ascii") as f:
        f.write("// fft_hann256.mem -- Hann window for FFT-256 = dsp_hann_q15[4n+2], tools/gen_mem.py\n")
        for n in range(256):
            f.write(f"{hann[4 * n + 2] & 0xFFFF:04x}\n")
    print("->", path)

    # GFSK для iq_gen: внесок біта з NRZ +-1 у миттєву частоту, коли до
    # початку поточного біта минуло u = p/256 бітового інтервалу.
    #   G(t) = 0.5*(erf(pi*t/a) - erf(pi*(t-1)/a)),  a = sqrt(ln2/2)/BT
    #   адреса j*256+p: j = 0 наступний біт (t = u-1), 1 поточний (t = u),
    #   2 попередній (t = u+1). Біти далі +-2 дають < 1e-7 -- відкинуто.
    bt = 0.5
    a = math.sqrt(math.log(2) / 2) / bt
    def g(t):
        return 0.5 * (math.erf(math.pi * t / a) - math.erf(math.pi * (t - 1) / a))
    path = os.path.join(MEM_DIR, "gen_gauss.mem")
    with open(path, "w", encoding="ascii") as f:
        f.write(f"// gen_gauss.mem -- GFSK BT {bt} pulse, 3 x 256 Q15 (next, current, previous bit), tools/gen_mem.py\n")
        for j, off in enumerate((-1.0, 0.0, 1.0)):
            for p in range(256):
                f.write(f"{q15(g(p / 256 + off)) & 0xFFFF:04x}\n")
    print("->", path)

    # ------------------------------------------------------------------ C ---
    path = os.path.join(SRC_DIR, "dsp_tables.c")
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* dsp_tables.c -- ЗГЕНЕРОВАНО tools/gen_mem.py, не редагувати вручну.\n"
                " *\n"
                " * dsp_sin_q15[k] = sin(2*pi*k/1024) для k = 0..256 (чверть періоду + 1),\n"
                " * dsp_hann_q15[n] = 0.5*(1 - cos(2*pi*n/1024)) для n = 0..1023.\n"
                " */\n")
        f.write('#include "dsp/dsp_tables.h"\n\n')
        f.write("const int16_t dsp_sin_q15[DSP_FFT_N / 4 + 1] = {\n")
        vals = [q15(math.sin(2 * math.pi * k / FFT_N)) for k in range(FFT_N // 4 + 1)]
        for i in range(0, len(vals), 12):
            f.write("    " + ", ".join(f"{v:6d}" for v in vals[i:i + 12]) + ",\n")
        f.write("};\n\n")
        f.write("const int16_t dsp_hann_q15[DSP_FFT_N] = {\n")
        vals = [q15(0.5 * (1 - math.cos(2 * math.pi * n / FFT_N))) for n in range(FFT_N)]
        for i in range(0, len(vals), 12):
            f.write("    " + ", ".join(f"{v:6d}" for v in vals[i:i + 12]) + ",\n")
        f.write("};\n")
    print("->", path)

    path = os.path.join(SRC_DIR, "dsp_tables.h")
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* dsp_tables.h -- ЗГЕНЕРОВАНО tools/gen_mem.py, не редагувати вручну. */\n"
                "#ifndef DSP_TABLES_H\n#define DSP_TABLES_H\n\n"
                "#include <stdint.h>\n\n"
                f"#define DSP_FFT_N {FFT_N}\n\n"
                "extern const int16_t dsp_sin_q15[DSP_FFT_N / 4 + 1];\n"
                "extern const int16_t dsp_hann_q15[DSP_FFT_N];\n\n"
                "#endif /* DSP_TABLES_H */\n")
    print("->", path)


if __name__ == "__main__":
    main()
